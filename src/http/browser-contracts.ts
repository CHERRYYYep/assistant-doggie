/** Generate browser-safe validation data from the executable HTTP operations. */
import { z } from "zod";

import { HTTP_OPERATIONS, type HttpOperation } from "./operations.ts";
import { errorResponseSchema } from "./response-schemas.ts";

export function createBrowserResponseContracts(): {
  readonly schemas: Readonly<Record<string, unknown>>;
  readonly operations: readonly {
    readonly method: string;
    readonly path: string;
    readonly schema: string;
  }[];
} {
  const schemas: Record<string, unknown> = {};
  const names = new Map<z.ZodType, string>();
  const register = (schema: z.ZodType, name: string): string => {
    const existing = names.get(schema);
    if (existing !== undefined) return existing;
    names.set(schema, name);
    const { $schema: _dialect, ...jsonSchema } = z.toJSONSchema(schema, {
      target: "draft-2020-12",
    });
    schemas[name] = jsonSchema;
    return name;
  };
  register(errorResponseSchema, "ErrorResponse");
  const operations = (HTTP_OPERATIONS as readonly HttpOperation[])
    .filter((operation) => operation.stream !== true)
    .map((operation) => ({
      method: operation.method,
      path: operation.path,
      schema: register(
        operation.responseSchema,
        `${operation.operationId}Response`,
      ),
    }));
  return { schemas, operations };
}

export function serializeBrowserResponseContracts(): string {
  return `/** Generated by node scripts/openapi.ts --write. Do not edit. */\n// prettier-ignore\nexport const RESPONSE_CONTRACTS = ${JSON.stringify(createBrowserResponseContracts(), null, 2)} as const;\n`;
}
